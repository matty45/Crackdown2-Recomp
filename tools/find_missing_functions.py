#!/usr/bin/env python3
"""Find code the recompiler's analysis never reaches and emit [functions] entries for default_functions.toml.

rexglue's gap-fill phase splits uncovered code only on blr and on known tail calls, so a vtable thunk that
ends in bctr swallows whatever follows it, and that code is never registered. The game then dies at run time
with "Call to invalid or unregistered function" the first time a function pointer lands there (Keys to the
City hit 0x824CF688, 0x8222D250 and 0x825C03D0 while loading the city).

This script needs a flat dump of the loaded image and the unwind table (both derived from the game files,
so they are not in the repo) plus the current generated/default/crackdown2_init.cpp:

    python tools/find_missing_functions.py image_82000000.bin pdata.csv generated/default/crackdown2_init.cpp

It prints the generated block; paste it over the "Generated by" block at the end of default_functions.toml,
rerun codegen, and fix any "Overlapping boundaries" / unresolved-call errors by removing the offending entry
(those are switch-table pieces inside a larger leaf function, not real entry points).

Selected fragments:
  * code that follows a bctr inside a function that has no unwind entry (the recompiler guessed its size);
  * code targets referenced from the data sections (vtables / function tables) that sit right after a
    terminator (blr, bctr, b) or padding.
Fragments inside an unwind-table range or inside an upstream-declared function are dropped; each size is
clipped to the next declared function start.
"""
import bisect
import re
import struct
import sys

BASE = 0x82000000
BLR, BCTR = 0x4E800020, 0x4E800420


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    image, pdata_csv, init_cpp = sys.argv[1:]
    d = open(image, "rb").read()

    def w(a):
        return struct.unpack_from(">I", d, a - BASE)[0]

    init = open(init_cpp).read()
    funcs = set(int(m, 16) for m in re.findall(r"\{\s*0x([0-9A-Fa-f]{8}),\s*\w+\s*\}", init))
    fs = sorted(funcs)
    text_lo, text_hi = fs[0], fs[-1] + 0x1000
    pd = {}
    for line in open(pdata_csv):
        p = line.strip().split(",")
        try:
            pd[int(p[0], 16)] = int(p[1])
        except (ValueError, IndexError):
            pass
    toml_dir = re.sub(r"generated/.*$", "", init_cpp) or "."
    head = open(f"{toml_dir}/default_functions.toml").read().split("# ---- Generated by")[0]
    upstream = {int(a, 16): int(s) for a, s in re.findall(r"^0x([0-9A-Fa-f]{8}) = \{[^}\n]*size = (\d+)", head, re.M)}
    upstream_keys = set(int(a, 16) for a in re.findall(r"^0x([0-9A-Fa-f]{8}) =", head, re.M))

    # Pointers from data sections into unregistered code.
    ptr = {}
    for off in range(0, len(d) - 4, 4):
        a = BASE + off
        if text_lo <= a < text_hi:
            continue
        v = struct.unpack_from(">I", d, off)[0]
        if text_lo <= v < text_hi and (v & 3) == 0 and v not in funcs and w(v) not in (0, 0xFFFFFFFF):
            ptr[v] = True

    def frag_end(s, nxt):
        e = s
        while e < nxt:
            k = w(e)
            e += 4
            if k in (BLR, BCTR):
                break
        return e

    sel = {}
    for i, a in enumerate(fs[:-1]):
        nxt = fs[i + 1]
        if a in pd:
            continue
        cur = a
        while cur < nxt:
            ins = w(cur)
            cur += 4
            if ins in (BCTR, BLR):
                s = cur
                while s < nxt and w(s) == 0:
                    s += 4
                if s < nxt and s not in funcs and (ins == BCTR or s in ptr):
                    sel[s] = frag_end(s, nxt) - s
                cur = s

    def prev_is_terminator(a):
        p = a - 4
        while p > BASE and w(p) == 0:
            p -= 4
        k = w(p)
        return k in (BLR, BCTR) or (k >> 26) == 18

    for v in ptr:
        if v in sel or not prev_is_terminator(v):
            continue
        i = bisect.bisect_right(fs, v)
        nxt = fs[i] if i < len(fs) else v + 0x1000
        size = frag_end(v, nxt) - v
        if size < 4096:
            sel[v] = size

    # Drop anything inside a known range; clip to the next declared start.
    ranges = sorted(list(upstream.items()) + list(pd.items()))
    starts = [a for a, _ in ranges]
    for a in list(sel):
        i = bisect.bisect_right(starts, a) - 1
        if a in upstream_keys or (i >= 0 and starts[i] < a < starts[i] + ranges[i][1]):
            del sel[a]
    all_starts = sorted(set(list(sel) + list(upstream_keys) + list(pd)))
    for a in list(sel):
        i = bisect.bisect_right(all_starts, a)
        if i < len(all_starts):
            sel[a] = min(sel[a], all_starts[i] - a)

    print("# ---- Generated by tools/find_missing_functions.py (do not edit by hand) ----")
    print("# Code the analysis never reaches on its own: vtable thunks and other fragments that follow a bctr")
    print("# (the gap-fill splitter only splits on blr and known tail calls), plus function-table targets that")
    print("# sit right after a terminator. See the script for how to regenerate this block.")
    for a, s in sorted(sel.items()):
        print(f"0x{a:08X} = {{ size = {s} }}")
    print(f"# {len(sel)} entries", file=sys.stderr)


if __name__ == "__main__":
    main()
